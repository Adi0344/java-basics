public class casting {
    public static void main(String[] args) {

        // type conversion

        byte b = 124;
        int a = b;
        System.out.println(a);

        // casting

        float f = 5.6f;
        int e = (int) f;
        System.out.println(e);

        // type promotion

        byte x = 10;
        byte y = 33;
        int result = x * y;
        System.out.println(result);

    }
}
